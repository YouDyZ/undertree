export interface LatexCommandEntry {
  label: string;
  snippet?: string;
  detail: string;
  type: "keyword" | "function" | "variable" | "constant" | "type";
  boost?: number;
}

export interface LatexEnvEntry {
  name: string;
  detail: string;
  /** Template inserted right after `\begin{name}` and before `\end{name}` */
  bodyTemplate?: string;
  boost?: number;
}

export function buildEnvSnippet(env: LatexEnvEntry): string {
  const body = env.bodyTemplate ?? "\n  ${1}";
  return `\\begin{${env.name}}${body}\n\\end{${env.name}}\${0}`;
}

